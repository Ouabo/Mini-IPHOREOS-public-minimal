"""Build the EXT1 explanatory video, following the same technique as
baseline_v1/Mini_IPHOREOS_Video/make_mini_iphoreos_video_en.py: PIL-rendered
frames piped through imageio_ffmpeg into a silent, English-captioned mp4.

Panels are redesigned for EXT1's richer trace schema (joint distance/speed
belief, context probabilities) rather than copying V1's panel layout
verbatim. Traces are read directly from results_ext1/ (seed 10000, already
generated by experiments/run_simulation.py) -- no new simulation is run here.
"""
from pathlib import Path
import json, math, hashlib
from PIL import Image, ImageDraw, ImageFont
import imageio_ffmpeg

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / 'results_ext1'
OUT = ROOT / 'Mini_IPHOREOS_EXT1_Video'
OUT.mkdir(exist_ok=True)


def load(name):
    rows = json.loads((RESULTS / name).read_text(encoding='utf-8'))
    for r in rows:
        r.setdefault('context_probabilities', {})
        r.setdefault('reason', r.get('realised_event', ''))
        r.setdefault('distance_sd', 0.6)
    return rows


TRACES = {
    'v1': load('trace_normal_v1.json'),
    'v1_fair': load('trace_normal_v1_fair.json'),
    'adaptive_no_information_normal': load('trace_normal_adaptive_no_information.json'),
    'ext1_bias': load('trace_bias_ext1.json'),
    'adaptive_no_information_bias': load('trace_bias_adaptive_no_information.json'),
}

FONT = Path('C:/Windows/Fonts')


def font(n, bold=False):
    return ImageFont.truetype(str(FONT / ('arialbd.ttf' if bold else 'arial.ttf')), n)


BG = '#0b1425'; CARD = '#14233a'; WHITE = '#eff5ff'; MUTED = '#a9bad1'
TEAL = '#49dbc3'; GOLD = '#ffcd70'; RED = '#ff7f88'


def text(draw, xy, t, size=24, color=WHITE, bold=False):
    draw.text(xy, t, font=font(size, bold), fill=color)


def lines(draw, xy, t, size=24, color=WHITE, gap=10):
    x, y = xy
    for line in t.split('\n'):
        text(draw, (x, y), line, size, color)
        y += size + gap


def base(title, sub, chapter):
    im = Image.new('RGB', (1280, 720), BG)
    d = ImageDraw.Draw(im)
    text(d, (36, 23), 'MINI-IPHOREOS EXTENDED SYSTEM  /  COGNITIVE EXTENSION, MILESTONE 1', 16, TEAL, True)
    text(d, (36, 56), title, 32, WHITE, True)
    text(d, (36, 101), sub, 18, MUTED)
    text(d, (36, 684), 'Desktop simulation \u2022 synthetic traces \u2022 no physical validation', 16, MUTED)
    text(d, (1060, 684), chapter, 16, TEAL)
    return im, d


LABEL = {'MOVE': 'MOVE', 'SAMPLE': 'MEASURE', 'DONE': 'DONE', 'ABORT': 'ABORT'}


def row_at(rows, progress):
    elapsed = progress * rows[-1]['simulator_time']
    idx = max(i for i, r in enumerate(rows) if r['simulator_time'] <= elapsed + 1e-9)
    return idx, rows[idx]


def panel(d, box, title, rows, progress, show_context=False):
    x, y, w, h = box
    d.rounded_rectangle((x, y, x + w, y + h), 16, fill=CARD)
    text(d, (x + 20, y + 14), title, 21, WHITE, True)
    idx, r = row_at(rows, progress)
    left = x + 36; right = x + w - 36; scale = (right - left) / 90

    def sx(v):
        return right - v * scale

    sy = y + 110
    d.rectangle((sx(29), sy - 24, sx(21), sy + 28), fill='#20564e')
    d.line((right, sy - 34, right, sy + 33), fill=WHITE, width=5)
    rx = sx(r['simulator_true_distance'])
    d.rounded_rectangle((rx - 40, sy - 16, rx, sy + 16), 5, fill=GOLD)
    d.ellipse((rx - 34, sy - 21, rx - 22, sy - 10), fill=MUTED)
    d.ellipse((rx - 34, sy + 10, rx - 22, sy + 21), fill=MUTED)
    text(d, (left, sy + 40), f"True: {r['simulator_true_distance']:.1f} cm (hidden from controller)", 16, GOLD)

    mu, sd = r['estimated_distance'], r['distance_sd']
    text(d, (left, y + 182), f"Belief: {mu:.1f} \u00b1 {sd:.2f} cm", 18, TEAL, True)
    if show_context:
        probs = r['context_probabilities']
        ps = probs.get('slow', None)
        info = r.get('speed_information_proxy')
        if ps is not None:
            text(d, (left, y + 208), f"P(slow context) = {ps:.2f}", 15, MUTED)
        if info is not None:
            text(d, (left + (230 if ps is not None else 0), y + 208), f"information proxy = {info:.2f}", 15, MUTED)

    gx = left; gy = y + 244; gw = w - 72; gh = 68
    d.line((gx, gy + gh, gx + gw, gy + gh), fill=MUTED)
    tmax = max(rows[-1]['simulator_time'], .01)

    def point(j, v):
        return (gx + gw * rows[j]['simulator_time'] / tmax, gy + gh * (1 - (v - 10) / 75))

    if idx > 0:
        upper = [point(j, rows[j]['estimated_distance'] + 1.64 * rows[j]['distance_sd']) for j in range(idx + 1)]
        lower = [point(j, rows[j]['estimated_distance'] - 1.64 * rows[j]['distance_sd']) for j in range(idx, -1, -1)]
        d.polygon(upper + lower, fill='#21504e')
        d.line([point(j, rows[j]['simulator_true_distance']) for j in range(idx + 1)], fill=GOLD, width=2)
        d.line([point(j, rows[j]['estimated_distance']) for j in range(idx + 1)], fill=TEAL, width=2)
    text(d, (gx, gy + gh + 6), 'Gold: true distance (hidden)   \u2022   Teal: belief \u00b1 1.64 sd', 13, MUTED)

    action = r['intended_option']
    text(d, (left, y + 346), 'DECISION: ' + LABEL.get(action, action), 20, TEAL if action != 'ABORT' else RED, True)
    text(d, (left, y + 373), str(r.get('reason', ''))[:48], 14, WHITE)
    text(d, (left, y + 395), f"move {r.get('moves_completed', 0)}  \u2022  t = {r['simulator_time']:.1f}s", 13, MUTED)
    return r


def frame(t):
    if t < 12:
        im, d = base('The Extended system: a cognitive extension of a simple controller',
                      'Joint distance/speed belief, inferred context, and a receding-horizon decision.', '1 / 5')
        lines(d, (65, 165), 'SAME TASK AS THE BASELINE SYSTEM\nApproach a wall; stop with the sensor 21-29 cm away.',
              27, WHITE, 14)
        lines(d, (65, 280),
              'The Extended system jointly estimates distance AND effective speed,\n'
              'maintains probabilities over two movement contexts\n(normal / slow),\n'
              'and can take a brief move specifically to learn about speed.',
              23, TEAL, 16)
        lines(d, (65, 480),
              'THIS RELEASE (Milestone 1) fixes two things found while\n'
              'evaluating the Extended system: an unfair comparison baseline, and a\nplanner that could get stuck waiting.',
              23, GOLD, 16)
    elif t < 52:
        im, d = base('01  /  A fair comparison for the Baseline system', "The Baseline system's rule only ever offered a 0.12s pulse. Same starting conditions, same seed.", '2 / 5')
        p = min(1, (t - 12) / 36)
        panel(d, (25, 150, 605, 500), "Baseline (original: 0.12s pulse only)", TRACES['v1'], p)
        panel(d, (650, 150, 605, 500), "Baseline fair (same rule, 0.12/0.24s menu)", TRACES['v1_fair'], p)
    elif t < 92:
        im, d = base('02  /  A planner that no longer stalls', 'Context ON, information-seeking OFF: the historically riskiest combination.', '3 / 5')
        p = min(1, (t - 52) / 38)
        r = panel(d, (120, 150, 1040, 500), 'adaptive_no_information  (two-step horizon + no-progress cost)', TRACES['adaptive_no_information_normal'], p, show_context=True)
        text(d, (160, 670), 'A one-step planner could prefer MEASURE forever once near the target; this one cannot.', 16, GOLD)
    elif t < 134:
        im, d = base('03  /  An open question: information-seeking under bias', 'Same unknown +5 cm sensor bias. Not yet a confirmed result -- same development seeds.', '4 / 5')
        p = min(1, (t - 92) / 40)
        panel(d, (25, 150, 605, 500), 'Extended (context + information-seeking)', TRACES['ext1_bias'], p, show_context=True)
        panel(d, (650, 150, 605, 500), 'adaptive_no_information (no information-seeking)', TRACES['adaptive_no_information_bias'], p, show_context=True)
    else:
        im, d = base('What Milestone 1 established', 'Addressed: fair comparators and a myopic planner. Not yet addressed: the rest of the roadmap.', '5 / 5')
        lines(d, (65, 165),
              'ADDRESSED THIS RELEASE\nSame action menu, observations and budget across every\n'
              'comparator (v1_fair, adaptive, adaptive_no_information,\n'
              'ext1_no_information, ext1). A two-step planner with an\nexplicit no-progress cost.',
              24, TEAL, 14)
        lines(d, (65, 380),
              'STILL OPEN\nReusable context memory \u2022 evidence-based change detection\n'
              '\u2022 an explicit sensor-bias reference \u2022 a frozen evaluation on\nheld-out seeds and conditions.',
              24, WHITE, 14)
        lines(d, (65, 540), 'See Mathematical_Model_EXT1.pdf for every equation shown in this video.', 20, GOLD, 14)
    return im


fps = 12; duration = 150
writer = imageio_ffmpeg.write_frames(str(OUT / 'EXT1_Explanation_EN.mp4'), (1280, 720), fps=fps,
                                      codec='libx264', pix_fmt_in='rgb24', pix_fmt_out='yuv420p',
                                      quality=7, macro_block_size=16)
writer.send(None)
for i in range(duration * fps):
    im = frame(i / fps)
    writer.send(im.tobytes())
    if i in (60, 240, 960, 1320, 1608):
        im.save(OUT / f'preview_EN_{i // fps}s.png')
    if i % (fps * 30) == 0:
        print(f'Video: {i // fps}/{duration}s', flush=True)
writer.close()

source_files = [ROOT / 'cognitive/controller.py', ROOT / 'cognitive/model.py', ROOT / 'cognitive/baselines.py']
manifest = {
    'duration_seconds': duration, 'fps': fps, 'resolution': [1280, 720],
    'source_sha256': {str(f.relative_to(ROOT)): hashlib.sha256(f.read_bytes()).hexdigest() for f in source_files},
    'traces_used': {
        'v1': 'trace_normal_v1.json', 'v1_fair': 'trace_normal_v1_fair.json',
        'adaptive_no_information_normal': 'trace_normal_adaptive_no_information.json',
        'ext1_bias': 'trace_bias_ext1.json', 'adaptive_no_information_bias': 'trace_bias_adaptive_no_information.json',
    },
    'notes': ('Silent English-captioned desktop simulation. Traces are seed 10000 from '
              'results_ext1/ (experiments/run_simulation.py), unmodified. The bias-scenario '
              'chapter shows an observed pattern from development seeds, not a frozen '
              'confirmatory result. No physical robot data or hardware validation is presented.')
}
(OUT / 'manifest_EN.json').write_text(json.dumps(manifest, indent=2), encoding='utf-8')
print('EXT1 video complete', flush=True)
